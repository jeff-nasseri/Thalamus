namespace Application.Common.Consts;

/// <summary>
///     Contains application-wide constant keys used throughout the application.
/// </summary>
public abstract class ApplicationKeys
{
    /// <summary>
    ///     The suffix used for resource file names.
    /// </summary>
    public const string RESOURCE_FILE_SUFFIX = "Resource";

    /// <summary>
    ///     The default message when no description is found.
    /// </summary>
    public const string NO_DESCRIPTION_FOUND = "NO-DESCRIPTION-FOUND";

    /// <summary>
    ///     The key for server main error message.
    /// </summary>
    public const string ERROR_SERVER_MAIN_MESSAGE = "server-main-message";
}